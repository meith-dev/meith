-- F46 — anti-spam: rate-limit counters and captcha questions.
--
-- ## `rate_limits` is a counter table, and the shape is the whole point
--
-- One row per (scope, subject, window), incremented by an insert-on-conflict
-- that returns the new total. **That single statement is the feature.** A
-- read-then-write would let ten requests arriving together each see nine and
-- each decide it was fine — and under an attack that interleaving is not rare,
-- it is the expected one, because flooding is exactly the traffic that arrives
-- in parallel. Postgres serialises the conflicting upserts for us; nothing in
-- application code can.
--
-- It is also why the limit is *multi-instance* in the sense the roadmap asks
-- for: the counter is a row rather than process state, so ten serverless
-- instances share one allowance instead of ten.
--
-- Fixed windows rather than a sliding log. A sliding window needs a row per
-- action and a scan to answer a question; this needs one row per subject per
-- window and answers by primary key. The cost is the boundary — a full
-- allowance at 10:59 and another at 11:00 — which for spam control is an
-- acceptable failure, because the attacker's reward is one extra window rather
-- than an unbounded one. Closing it would make the anti-spam feature the
-- board's largest table.
--
-- `subject` is text rather than a user id because a guest has no id: it holds
-- `u:<id>` for a member and `ip:<prefix>` for a guest, built in one place
-- (`subjectFor`). The prefix is F09's already-truncated address — enough to
-- group by, not enough to identify somebody by.
--
-- No foreign key to `users`, deliberately. A limit row is not a fact about a
-- member worth keeping, and a cascade on account deletion would be a write
-- amplification on a table that is otherwise pure append-and-prune.

CREATE TABLE "rate_limits" (
	-- One of the five F46 names: post, search, message, report, upload.
	"scope" text NOT NULL,
	"subject" text NOT NULL,
	"window_start" timestamp with time zone NOT NULL,
	"used" integer DEFAULT 0 NOT NULL,
	CONSTRAINT "rate_limits_pkey" PRIMARY KEY ("scope", "subject", "window_start")
);
