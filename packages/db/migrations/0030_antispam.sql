-- ## `captcha_questions`
--
-- Admin-defined question-and-answer challenges. Answers are stored as text and
-- compared case-insensitively after trimming and collapsing internal spaces —
-- an operator writing "Blue" and a visitor typing "blue " is not a failed
-- challenge, and treating it as one teaches people the form is broken.
--
-- The answers are **not** hashed. They are not secrets: the question is shown
-- to everybody, an attacker can read the answer by registering once, and the
-- control is aimed at scripts rather than at people. Hashing them would cost
-- the ACP the ability to show an operator what they configured, in exchange for
-- protecting a value that is public by construction.
CREATE TABLE "captcha_questions" (
	"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (sequence name "captcha_questions_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"question" text NOT NULL,
	-- One per line, as the operator typed them. Any one satisfies the challenge.
	"answers" text NOT NULL,
	"enabled" boolean DEFAULT true NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL
);
