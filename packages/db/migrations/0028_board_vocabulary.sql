CREATE TABLE "custom_bbcode" (
	"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (sequence name "custom_bbcode_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	-- 1–16 letters or digits, starting with a letter. Lower-cased on the way in,
	-- because `[Spoiler]` and `[spoiler]` are the same tag to the tokeniser and
	-- storing both would be two rows the registry refuses to build from.
	"name" text NOT NULL,
	-- Block tags render as a `div`, inline as a `span`. That is the only choice.
	"block" boolean DEFAULT false NOT NULL,
	-- For the operator, never rendered. A note about what the tag is for.
	"description" text,
	"enabled" boolean DEFAULT true NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL
);
--> statement-breakpoint
CREATE UNIQUE INDEX "custom_bbcode_name_key" ON "custom_bbcode" ("name");
