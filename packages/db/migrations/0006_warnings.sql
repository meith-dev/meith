-- What happens when a member's total reaches a threshold.
--
-- Levels are *thresholds*, not steps: the level that applies is the
-- highest-pointed one the member has reached, so removing a level or inserting
-- one between two others changes future evaluations and never leaves a member
-- stranded at a level that no longer exists. Re-evaluated from the recomputed
-- total after every change, which is what makes a revocation actually lift a
-- restriction rather than only lowering a number.
CREATE TABLE "warning_levels" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  "points" smallint NOT NULL,
  -- 'suspend_posting' | 'moderate_posting' | 'ban'. Text rather than an enum,
  -- for the reason `visibility` is: adding an action must not need a type
  -- migration.
  "action" text NOT NULL,
  -- NULL = for as long as the member is at this level. A duration makes the
  -- restriction outlive the points; without one it lifts when they do.
  "duration_days" integer,
  "created_at" timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT "warning_levels_points_unique" UNIQUE ("points")
);
--> statement-breakpoint

-- One issued warning. The record; `users.warning_points` is the cache of it.
CREATE TABLE "warnings" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  "user_id" integer NOT NULL REFERENCES "users"("id") ON DELETE cascade,
  "issued_by_user_id" integer REFERENCES "users"("id") ON DELETE SET NULL,

  -- The type it came from, and the values *as they were at the time*. A type
  -- whose points are edited from 3 to 1 next year must not silently rewrite
  -- every warning ever issued under it — a member's history is a record of what
  -- they were told, not a view over current configuration.
  "type_id" integer REFERENCES "warning_types"("id") ON DELETE SET NULL,
  "title" text NOT NULL,
  "points" smallint NOT NULL,
  "reason" text NOT NULL DEFAULT '',

  -- What it was about, when it was about something. Both nullable: a warning
  -- can be issued for conduct with no single artefact behind it.
  "post_id" integer REFERENCES "posts"("id") ON DELETE SET NULL,
  "report_id" integer REFERENCES "reports"("id") ON DELETE SET NULL,

  "created_at" timestamp with time zone NOT NULL DEFAULT now(),
  -- NULL = never expires.
  "expires_at" timestamp with time zone,

  -- Revocation is a column pair rather than a deletion, because "this warning
  -- was withdrawn" is information a member is entitled to and a moderator needs.
  -- A deleted row cannot say a mistake was corrected.
  "revoked_at" timestamp with time zone,
  "revoked_by_user_id" integer REFERENCES "users"("id") ON DELETE SET NULL,
  "revoke_reason" text
);
--> statement-breakpoint

-- The history read: one member's warnings, newest first.
CREATE INDEX "warnings_user_idx" ON "warnings" ("user_id", "created_at" DESC, "id" DESC);
--> statement-breakpoint

-- The recalculation read, and the only one that runs on a hot path. Partial,
-- because a board's warnings are overwhelmingly expired or revoked and only the
-- live ones are ever summed.
CREATE INDEX "warnings_live_idx"
  ON "warnings" ("user_id")
  INCLUDE ("points", "expires_at")
  WHERE "revoked_at" IS NULL;
--> statement-breakpoint

-- The expiry sweep: warnings past their date that still count. Acts on
-- outstanding state rather than "what expired since the last run", which is
-- what makes a skipped tick cost a delay and nothing else (F06).
CREATE INDEX "warnings_expiry_idx"
  ON "warnings" ("expires_at")
  WHERE "revoked_at" IS NULL AND "expires_at" IS NOT NULL;
--> statement-breakpoint

-- The two restrictions a warning level can impose, on the row the posting path
-- already reads.
--
-- Columns rather than a `user_restrictions` table because there is at most one
-- of each per member and the posting path needs both on every post: a join for
-- a row that is almost always absent is a join on the board's hottest write.
-- NULL means no restriction; a timestamp in the past is one that has lapsed and
-- is treated as absent, so nothing has to be swept for correctness.
ALTER TABLE "users" ADD COLUMN "suspended_posting_until" timestamp with time zone;
