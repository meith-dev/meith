-- F53 — warnings.
--
-- `users.warning_points` has existed since 0000 with nothing that writes it.
-- This is what writes it, and the shape follows from one decision: **the column
-- is a cache of the live warnings, never the record itself.**
--
-- A points *total* that is incremented and decremented cannot survive a
-- revocation. Revoking a three-point warning issued four months ago has to
-- subtract three from a number that has since been decremented by two expiries
-- and incremented by a fourth warning, and if any one of those steps was missed
-- the total is wrong with nothing to compare it against. So the total is
-- recomputed from `warnings` — where every issue, expiry and revocation is a
-- row — after anything changes it. That is the same argument F38 makes for
-- `PostgresCounterRecount`, applied to a counter small enough to recompute
-- every time rather than on a schedule.
--
-- What is deliberately absent: notifying the warned member (F55 has no
-- notification path), and any admin surface for editing types or levels (F66's
-- screen). Omitted rather than stubbed, per D32.

-- The reusable reasons a moderator picks from.
--
-- A warning may also be free-text, which is why `warnings.type_id` is nullable:
-- a board that has not configured any types must still be able to warn somebody,
-- or the feature does not exist until an administrator visits a screen that
-- does not exist yet either.
CREATE TABLE "warning_types" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  "title" text NOT NULL,
  "points" smallint NOT NULL DEFAULT 1,
  -- NULL = never expires. Not 0, which would be indistinguishable from
  -- "expires immediately" and is the sentinel D-for-promotions already refused.
  "expiry_days" integer,
  "is_active" boolean NOT NULL DEFAULT true,
  "display_order" integer NOT NULL DEFAULT 0,
  "created_at" timestamp with time zone NOT NULL DEFAULT now(),
  "updated_at" timestamp with time zone NOT NULL DEFAULT now()
);
