-- The staff ladder gets it. Moderators included: warning somebody is the
-- proportionate response to most of what a moderator finds, and a moderator who
-- can only delete posts has one tool for every problem.
UPDATE "usergroups" SET "can_warn_users" = true
 WHERE "key" IN ('administrators', 'super_moderators', 'moderators');
