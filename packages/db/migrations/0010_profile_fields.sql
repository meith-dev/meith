-- The per-group override, in F21's shape.
--
-- NULL means inherit, which is what makes "staff may edit this" one row rather
-- than a row per group with the other answer copied into it. The resolution is
-- R4.2's: any group granting is a grant.
CREATE TABLE "profile_field_groups" (
  "field_id" integer NOT NULL REFERENCES "profile_fields"("id") ON DELETE cascade,
  "group_id" integer NOT NULL REFERENCES "usergroups"("id") ON DELETE cascade,
  "can_view" boolean,
  "can_edit" boolean,
  CONSTRAINT "profile_field_groups_pkey" PRIMARY KEY ("field_id", "group_id")
);
--> statement-breakpoint

-- One member's answer to one field.
--
-- A row exists only once somebody answers, so an unanswered field costs
-- nothing — which matters when a board with twelve fields has ten thousand
-- members who filled in two.
CREATE TABLE "profile_field_values" (
  "user_id" integer NOT NULL REFERENCES "users"("id") ON DELETE cascade,
  "field_id" integer NOT NULL REFERENCES "profile_fields"("id") ON DELETE cascade,
  "value" text NOT NULL DEFAULT '',
  "updated_at" timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT "profile_field_values_pkey" PRIMARY KEY ("user_id", "field_id")
);
--> statement-breakpoint

-- The profile read: one member's answers. The postbit read is the same shape
-- for one author at a time.
CREATE INDEX "profile_field_values_user_idx" ON "profile_field_values" ("user_id");
