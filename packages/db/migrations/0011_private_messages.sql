-- One person's copy of one message.
--
-- `folder` is a system folder rather than a foreign key to a user-defined one.
-- Custom folders need a management screen and a move-to picker with an
-- unbounded list; the three below are what makes the feature work, and the
-- fourth state MyBB has (drafts) belongs to F44, which has no table.
CREATE TABLE "private_message_copies" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  "message_id" integer NOT NULL REFERENCES "private_messages"("id") ON DELETE cascade,
  "owner_user_id" integer NOT NULL REFERENCES "users"("id") ON DELETE cascade,

  -- 'inbox' | 'sent' | 'trash'. Text rather than an enum, like every other
  -- state column on this board: adding a folder must not need a type migration.
  "folder" text NOT NULL DEFAULT 'inbox',

  -- 'author' | 'to' | 'bcc'. What this copy records, which is not the same
  -- question as which folder it is in — a sender who trashes their Sent copy
  -- is still the author.
  "role" text NOT NULL DEFAULT 'to',

  -- NULL means unread. A timestamp rather than a boolean because the sender's
  -- tracking screen wants *when*, and "read" is `read_at IS NOT NULL`.
  "read_at" timestamp with time zone,

  "created_at" timestamp with time zone NOT NULL DEFAULT now(),

  -- One copy per person per message. This is also the dedupe for a sender who
  -- names the same recipient twice, and the reason sending to yourself is
  -- refused in the service rather than handled with a second row.
  CONSTRAINT "private_message_copies_unique" UNIQUE ("message_id", "owner_user_id")
);
