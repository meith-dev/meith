-- F60 — private messages.
--
-- Two tables, and the split is the one decision everything else follows from:
-- **the message is stored once, and each participant owns a *copy* of it.**
--
-- MyBB stores a row per copy — sender's Sent Items and every recipient's Inbox
-- each hold the full subject and body — so a message to twenty people is twenty
-- copies of the text, and editing or re-rendering one is twenty writes. Here
-- `private_messages` holds the content and `private_message_copies` holds one
-- small row per person: which folder they filed it in, whether they have read
-- it, and when. Quota then counts *copies*, which is the thing a member can
-- actually delete.
--
-- The cost is a join on every listing, which is what the two indexes at the
-- bottom exist for.

CREATE TABLE "private_messages" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- SET NULL rather than cascade: deleting an account must not silently delete
  -- messages other people still hold. The username is captured alongside for
  -- the same reason F49 captures a target label — the row has to stay readable.
  "author_user_id" integer REFERENCES "users"("id") ON DELETE SET NULL,
  "author_username" text NOT NULL DEFAULT '',

  "subject" text NOT NULL,

  -- Raw BBCode and F36's render cache, exactly as `posts` carries them. A PM
  -- body is the same kind of thing a post body is, rendered by the same
  -- renderer at the same version, so a security fix to the renderer takes
  -- effect here on the next page load like it does everywhere else.
  "message" text NOT NULL,
  "message_html" text,
  "render_version" smallint NOT NULL DEFAULT 0,

  -- The message this one answers, so a reply can show what it replied to.
  -- SET NULL: the parent may be deleted by everybody who held a copy.
  "reply_to_id" integer REFERENCES "private_messages"("id") ON DELETE SET NULL,

  -- The sender asked to be told when it is read (F60's read receipt). The
  -- *tracking* half needs no flag — `read_at` below is recorded either way —
  -- so this column only decides whether a notification is raised.
  "receipt_requested" boolean NOT NULL DEFAULT false,

  "sent_at" timestamp with time zone NOT NULL DEFAULT now()
);
