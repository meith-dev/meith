-- How many messages a member may *keep* (F60).
--
-- Distinct from `max_private_messages_per_day`, which has existed since `0000`
-- and is a send *rate*. This one is storage, and it is what a full inbox means.
-- 0 = unlimited, like every other numeric permission, so the default here is
-- the deny-by-default fallback in name only: the seed below gives the real
-- per-group values.
ALTER TABLE "usergroups" ADD COLUMN "private_message_quota" integer DEFAULT 0 NOT NULL;
--> statement-breakpoint

-- The ladder, matching `0001`'s shape: members get a bounded box, staff do not.
-- A guest cannot hold a message at all, and its 0 is unreachable rather than
-- generous — `can_use_private_messages` is false for that group.
UPDATE "usergroups" SET "private_message_quota" = 100 WHERE "key" = 'registered';
