-- The folder listing: one member's copies in one folder, newest first.
--
-- `id` breaks the tie because two messages can share a second, and a listing
-- whose order is not total pages inconsistently — the same argument F40's
-- keyset cursor makes.
CREATE INDEX "private_message_copies_folder_idx"
  ON "private_message_copies" ("owner_user_id", "folder", "id" DESC);
--> statement-breakpoint

-- The unread badge, and the count on the folder tabs. Partial, because unread
-- is the small set and the index should not carry a board's whole history of
-- read mail to answer "how many are new".
CREATE INDEX "private_message_copies_unread_idx"
  ON "private_message_copies" ("owner_user_id")
  WHERE "read_at" IS NULL AND "folder" = 'inbox';
--> statement-breakpoint

-- The sender's tracking view: every copy of one message.
CREATE INDEX "private_message_copies_message_idx"
  ON "private_message_copies" ("message_id");
--> statement-breakpoint

-- F36's backfill predicate, for the same reason `posts` has one: a stale render
-- is a live render, and the task rewrites them in bounded batches.
CREATE INDEX "private_messages_render_version_idx"
  ON "private_messages" ("render_version", "id");
