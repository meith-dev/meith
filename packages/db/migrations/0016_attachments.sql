-- Two objects can never share a key, which is what makes deleting one row's
-- object safe without checking whether another row points at it.
CREATE UNIQUE INDEX "attachments_storage_key_key" ON "attachments" ("storage_key")
  WHERE "storage_key" IS NOT NULL;
