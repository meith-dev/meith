-- Every object written to the store, from the moment it is written.
--
-- A row is inserted *before* the `put`, and deleted when an `attachments` row
-- takes ownership of the key or when the object is deleted. What is left is
-- exactly the set of keys that may exist in the bucket with nothing pointing at
-- them: a crash between the put and the insert, a post that failed validation
-- after its files were stored, a processing job that died between writing the
-- re-encoded object and updating the row.
--
-- The alternative is listing the bucket and diffing it against the table, which
-- costs a full scan of both and is wrong the moment an upload is in flight.
CREATE TABLE "attachment_orphans" (
  "storage_key" text PRIMARY KEY,
  "created_at" timestamp with time zone NOT NULL DEFAULT now()
);
--> statement-breakpoint

-- The sweep, oldest first, with a grace period so an in-flight upload is never
-- collected out from under itself.
CREATE INDEX "attachment_orphans_age_idx" ON "attachment_orphans" ("created_at");
