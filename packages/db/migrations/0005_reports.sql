-- F49 — reports.
--
-- A report is a member saying "a moderator should look at this". Two tables,
-- because a report has a *current state* and a *history*, and collapsing them
-- loses the second: "who assigned this to me and when" is the question a
-- moderator picking up somebody else's work actually asks.
--
-- What is deliberately absent: private messages as a target (F60 has no tables
-- yet) and notifications on state changes (F55). Omitted rather than stubbed —
-- a `pm` kind nothing can produce is a column that lies about what the board
-- supports.

CREATE TABLE "reports" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- 'post' | 'thread' | 'user'. Text rather than an enum for the same reason
  -- `visibility` is: adding a kind must not need a type migration.
  "target_kind" text NOT NULL,
  "target_id" integer NOT NULL,

  -- Denormalised from the target, and null for a user report. This is what
  -- scopes the moderator list by `moderatedCommunityIds` without joining three
  -- tables per row — and it is what keeps a report readable after its target
  -- is hard-deleted.
  "community_id" integer REFERENCES "communities"("id") ON DELETE SET NULL,
  -- Likewise: the thread a post report is in, so the list can link to it.
  "thread_id" integer REFERENCES "threads"("id") ON DELETE SET NULL,
  -- A label captured at report time. The target may be edited or removed
  -- afterwards, and a moderator needs to know what was complained about.
  "target_label" text NOT NULL DEFAULT '',

  "reporter_user_id" integer REFERENCES "users"("id") ON DELETE SET NULL,
  "reason" text NOT NULL,

  -- 'open' | 'resolved' | 'rejected'. Assignment is a separate column rather
  -- than a status, because an assigned report is still open — modelling it as a
  -- state means "show me everything outstanding" has to list two of them.
  "status" text NOT NULL DEFAULT 'open',
  "assigned_to_user_id" integer REFERENCES "users"("id") ON DELETE SET NULL,

  "resolved_by_user_id" integer REFERENCES "users"("id") ON DELETE SET NULL,
  "resolved_at" timestamp with time zone,

  "created_at" timestamp with time zone NOT NULL DEFAULT now(),
  "updated_at" timestamp with time zone NOT NULL DEFAULT now()
);
