-- The history, and the only place a private moderator note lives.
--
-- Notes are on the *event*, not the report, so "resolved because X" stays
-- attached to the resolution rather than being overwritten by the next one.
-- Nothing in this table is ever shown to the reporter.
CREATE TABLE "report_events" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  "report_id" integer NOT NULL REFERENCES "reports"("id") ON DELETE cascade,
  "actor_user_id" integer REFERENCES "users"("id") ON DELETE SET NULL,
  -- 'opened' | 'assigned' | 'unassigned' | 'resolved' | 'rejected' | 'note'
  "kind" text NOT NULL,
  "note" text,
  "created_at" timestamp with time zone NOT NULL DEFAULT now()
);
