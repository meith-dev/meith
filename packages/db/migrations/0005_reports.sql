-- One open report per person per target.
--
-- Not a nicety: without it, "report" is a button that adds a row to the
-- moderation queue on every click, which makes it the cheapest denial-of-
-- service on the board. Partial, so the same person may report the same post
-- again after a previous report was closed — circumstances change.
CREATE UNIQUE INDEX IF NOT EXISTS "reports_one_open_per_reporter_key"
  ON "reports" ("reporter_user_id", "target_kind", "target_id")
  WHERE "status" = 'open' AND "reporter_user_id" IS NOT NULL;
