-- One import at a time. A second concurrent run would interleave two cursor
-- sets over one destination, and the failure — rows imported twice under
-- different ids — is exactly what the idempotency was meant to prevent.
CREATE UNIQUE INDEX "import_runs_one_running_idx" ON "import_runs" ("source")
	WHERE "status" = 'running';
