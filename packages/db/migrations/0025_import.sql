-- One row per import, holding the cursors.
--
-- The cursors are *legacy ids*, which is what makes a run resumable across
-- processes: an offset would mean something different on the next run, because
-- the source board is usually still being posted to during a migration.
CREATE TABLE "import_runs" (
	"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	"source" text DEFAULT 'mybb' NOT NULL,
	-- { users, communities, threads, posts } — a legacy id per kind.
	"cursors" jsonb DEFAULT '{}'::jsonb NOT NULL,
	-- running | finished | failed
	"status" text DEFAULT 'running' NOT NULL,
	"rows_read" integer DEFAULT 0 NOT NULL,
	"report" jsonb DEFAULT '{}'::jsonb NOT NULL,
	"last_error" text,
	"started_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL
);
