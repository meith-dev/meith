-- F85 — the MyBB import's two tables.
--
-- `legacy_ids` is the one F86 depends on: every old URL contains a MyBB id, so
-- redirecting `/showthread.php?tid=91` means knowing which thread that became.
-- Without it an import is a one-way door that breaks every inbound link a board
-- has accumulated — which for a community is most of its traffic.
CREATE TABLE "legacy_ids" (
	-- 'user' | 'community' | 'thread' | 'post'
	"kind" text NOT NULL,
	"legacy_id" integer NOT NULL,
	"new_id" integer NOT NULL,
	"imported_at" timestamp with time zone DEFAULT now() NOT NULL,
	PRIMARY KEY ("kind", "legacy_id")
);
