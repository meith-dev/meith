-- F62 — reputation.
--
-- One table, and the interesting part is that **the two rate limits are two
-- different mechanisms, because they are two different shapes.**
--
--   * "One rating per person per target" is a *uniqueness* rule, and it is
--     enforced by a unique index — the same trick F49's duplicate-report guard
--     uses (D48). A check-then-insert would let two clicks arriving together
--     both pass, and a reputation button that adds a row on every click is the
--     cheapest way to inflate a total.
--   * "At most N a day" is a *window*, which no index can express. It is a
--     count inside the writing transaction, and its residual race is stated
--     rather than hidden: two concurrent inserts can both see N-1 and both
--     commit, so the real ceiling is N+1 for somebody scripting it. That is a
--     rate limit, not a permission, and being one over is not a security event.
--
-- `users.reputation` has existed since `0000` with **no writer**. It gets one
-- here, and it is **derived, never incremented** — recomputed from the live
-- rows in the same transaction as anything that changes them, exactly as F53
-- does with `warning_points`. An incremented total cannot survive a rating
-- being revised or withdrawn, and drifts silently when it does.

CREATE TABLE "reputation" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- Who it is about.
  "user_id" integer NOT NULL REFERENCES "users"("id") ON DELETE cascade,

  -- Who gave it. SET NULL rather than cascade: removing an account must not
  -- silently rewrite everybody else's totals, and the recount below treats a
  -- null giver as a rating that still counts. Somebody's reputation is a record
  -- of what the board thought, not a list of currently-active accounts.
  "given_by_user_id" integer REFERENCES "users"("id") ON DELETE SET NULL,

  -- The post it is about, or NULL for a rating left on the profile. Two shapes
  -- with two uniqueness rules; see the indexes below.
  "post_id" integer REFERENCES "posts"("id") ON DELETE cascade,

  -- Bounded by the service, not by the column: a board that later allows ±2
  -- should not need a migration. smallint because the value is single digits
  -- and the *total* is the integer column on `users`.
  "points" smallint NOT NULL DEFAULT 1,

  -- Why. Required or optional by board setting; stored as plain text and
  -- rendered as plain text — a reputation comment is short, is shown on a
  -- profile every member can visit, and has no reason to carry markup.
  "comment" text NOT NULL DEFAULT '',

  "created_at" timestamp with time zone NOT NULL DEFAULT now(),
  "updated_at" timestamp with time zone NOT NULL DEFAULT now()
);
