-- One profile rating per pair, ever.
--
-- Partial, because a member may also rate any number of that person's *posts*.
-- Re-rating somebody updates this row rather than adding a second, which is
-- what makes "change your mind" a supported act instead of a way to stack
-- points.
CREATE UNIQUE INDEX "reputation_profile_unique"
  ON "reputation" ("given_by_user_id", "user_id")
  WHERE "post_id" IS NULL;
--> statement-breakpoint

-- One rating per person per post.
CREATE UNIQUE INDEX "reputation_post_unique"
  ON "reputation" ("given_by_user_id", "post_id")
  WHERE "post_id" IS NOT NULL;
--> statement-breakpoint

-- The history screen: everything about one member, newest first.
CREATE INDEX "reputation_user_idx" ON "reputation" ("user_id", "id" DESC);
--> statement-breakpoint

-- The daily cap's count, and "what have I given" on somebody's own screen.
CREATE INDEX "reputation_given_idx"
  ON "reputation" ("given_by_user_id", "created_at" DESC);
